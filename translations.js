// Current language (default: Russian)
let currentLang = localStorage.getItem('atriLang') || 'ru';

// Get translation by key
function t(key) {
    if (translations[key] && translations[key][currentLang]) {
        return translations[key][currentLang];
    }
    return translations[key]?.ru || key;
}

// Get character data
function getCharacter(charKey) {
    const char = charactersData[charKey];
    if (!char) return null;
    return {
        image: char.image,
        name: char.name[currentLang] || char.name.ru,
        age: char.age[currentLang] || char.age.ru,
        desc: char.desc[currentLang] || char.desc.ru,
        quote: char.quote[currentLang] || char.quote.ru
    };
}

// Get music track name
function getTrackName(index) {
    const track = musicTracksData[index];
    if (!track) return "";
    return track.name[currentLang] || track.name.ru;
}

// Apply all translations to the page
function applyTranslations() {
    // Animate text change
    const animateTextChange = (element, newText, isHTML = false) => {
        if (!element) return;

        element.style.transition = 'opacity 0.3s ease, transform 0.3s ease, filter 0.3s ease';
        element.style.opacity = '0';
        element.style.transform = 'scale(0.95)';
        element.style.filter = 'blur(5px)';

        setTimeout(() => {
            if (isHTML) {
                element.innerHTML = newText;
            } else {
                element.textContent = newText;
            }
            element.style.opacity = '1';
            element.style.transform = 'scale(1)';
            element.style.filter = 'blur(0)';

            // Clean up inline styles after animation to allow CSS hover/animations to work
            setTimeout(() => {
                element.style.transition = '';
                element.style.opacity = '';
                element.style.transform = '';
                element.style.filter = '';
            }, 300);
        }, 300);
    };

    // Section 1
    animateTextChange(document.querySelector('.logo'), t('logo'));
    animateTextChange(document.querySelector('.hero-text'), t('heroText'), true);

    const startBtn = document.querySelector('.start-button');
    if (startBtn) {
        const btnText = startBtn.childNodes[0];
        if (btnText && btnText.nodeType === Node.TEXT_NODE) {
            setTimeout(() => {
                btnText.textContent = t('startButton') + '\n';
            }, 300);
        }
        const btnSub = startBtn.querySelector('.button-subtitle');
        if (btnSub) animateTextChange(btnSub, t('startButtonSub'));
    }

    const scrollInd = document.querySelector('.scroll-indicator');
    if (scrollInd) {
        const textNode = scrollInd.childNodes[0];
        if (textNode && textNode.nodeType === Node.TEXT_NODE) {
            setTimeout(() => {
                textNode.textContent = t('scrollHint') + '\n';
            }, 300);
        }
    }

    // Section 2
    animateTextChange(document.querySelector('.characters-title'), t('charactersTitle'));

    // Section 3
    animateTextChange(document.querySelector('.features-title'), t('featuresTitle'));

    const featureTexts = document.querySelectorAll('.feature-text');
    if (featureTexts[0]) animateTextChange(featureTexts[0], t('feature1Text'));
    if (featureTexts[1]) animateTextChange(featureTexts[1], t('feature2Text'));
    if (featureTexts[2]) animateTextChange(featureTexts[2], t('feature3Text'));

    animateTextChange(document.getElementById('sectionHint'), t('sectionHint'));

    // Section 4
    animateTextChange(document.querySelector('.action-title'), t('actionTitle'));
    animateTextChange(document.querySelector('.novel-btn'), t('novelBtn'));
    animateTextChange(document.querySelector('.anime-btn'), t('animeBtn'));

    // Modals
    const novelModalTitle = document.querySelector('#novelModal .modal-title');
    const animeModalTitle = document.querySelector('#animeModal .modal-title');
    if (novelModalTitle) animateTextChange(novelModalTitle, t('novelModalTitle'));
    if (animeModalTitle) animateTextChange(animeModalTitle, t('animeModalTitle'));

    // Steam Link
    const steamLink = document.querySelector('#steamLink');
    if (steamLink) animateTextChange(steamLink, t('steamBtn'));

    // Character Banners (Carousel)
    const charCards = document.querySelectorAll('.character-card');
    charCards.forEach(card => {
        const charKey = card.dataset.char;
        if (typeof getCharacter === 'function') {
            const charData = getCharacter(charKey);
            if (charData) {
                const nameEl = card.querySelector('.character-card-name');
                if (nameEl) animateTextChange(nameEl, charData.name);
            }
        }
    });

    // Player
    animateTextChange(document.querySelector('.player-title'), t('playerTitle'));

    // Update track names in player
    const trackItems = document.querySelectorAll('.track-item .track-name');
    trackItems.forEach((item, index) => {
        animateTextChange(item, getTrackName(index));
    });

    // Update current character info
    const activeCard = document.querySelector('.character-card.active');
    if (activeCard) {
        const charKey = activeCard.dataset.char;
        updateCharacterDisplay(charKey, false); // false = no card animation
    }

    // Save preference
    localStorage.setItem('atriLang', currentLang);
}

// Update character display with current language
function updateCharacterDisplay(charKey, animateImage = true) {
    const char = getCharacter(charKey);
    if (!char) return;

    const infoCard = document.getElementById('characterInfoCard');
    const nameEl = document.getElementById('infoName');
    const ageEl = document.getElementById('infoAge');
    const descEl = document.getElementById('infoDesc');

    if (nameEl) nameEl.textContent = char.name;
    if (ageEl) ageEl.textContent = char.age;
    if (descEl) descEl.textContent = char.desc;

    // Update quote with typewriter
    if (typeof typeWriter === 'function') {
        const rawQuote = char.quote.replace(/^"|"$/g, '');
        typeWriter(`"${rawQuote}"`, 'characterQuote');
    }
}

// Change language
function changeLanguage(lang) {
    if (lang === currentLang) return;
    currentLang = lang;
    applyTranslations();

    // Update language button display
    const langBtn = document.getElementById('langBtn');
    if (langBtn) {
        const flags = { ru: '🇷🇺', en: '🇬🇧', zh: '🇨🇳', ja: '🇯🇵' };
        langBtn.querySelector('.lang-flag').textContent = flags[lang] || '🌐';
    }

    // Close dropdown
    const dropdown = document.getElementById('langDropdown');
    if (dropdown) dropdown.classList.remove('active');
}

// Initialize on load
document.addEventListener('DOMContentLoaded', () => {
    // Apply saved language
    if (currentLang !== 'ru') {
        applyTranslations();
    }
});
